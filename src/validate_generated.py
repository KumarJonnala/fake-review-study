def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--generated", type=Path, default=cfg.DEFAULT_OUTPUT)
    p.add_argument("--examples-csv", type=Path, default=cfg.DEFAULT_EXAMPLES_CSV)
    p.add_argument("--host", default=cfg.DEFAULT_HOST)
    p.add_argument("--model", default=cfg.DEFAULT_MODEL, help="Model used for the judge")
    p.add_argument("--length-tolerance", type=float, default=cfg.DEFAULT_LENGTH_TOLERANCE)
    p.add_argument("--no-judge", action="store_true",
                   help="Skip the LLM sentiment judge (no Ollama needed)")
    args = p.parse_args(argv)

    if not args.generated.exists():
        sys.exit(f"No generated CSV at {args.generated}")

    gen = pd.read_csv(args.generated)
    hum = pd.read_csv(args.examples_csv)
    url = f"http://{args.host}{cfg.OLLAMA_CHAT_PATH}"

    print(f"Generated: {args.generated}  ({len(gen)} reviews, "
          f"{gen.cell_id.nunique()}/{len(ALL_CELLS)} cells)")
    print(f"Corpus:    {args.examples_csv}  ({len(hum)} human reviews)")

    recovered = reconstruct_instructions(gen, args.examples_csv, args.length_tolerance)

    report_length(gen, args.length_tolerance)
    report_sentiment(gen, url, args.model, use_judge=not args.no_judge)
    report_structure(gen, recovered)
    report_example_mode(gen, recovered)
    report_opener(gen, recovered)
    report_stylometry(gen, hum)
    flagged = report_perfect_separators(gen, hum)
    report_hygiene(gen)

    print()
    # Non-zero exit on a perfect separator: this is the failure mode that silently
    # invalidates the whole dataset, so it should break a pipeline, not just print.
    return 1 if flagged else 0


if __name__ == "__main__":
    sys.exit(main())

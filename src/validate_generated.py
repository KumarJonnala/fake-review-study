# Aspect detection
# ---------------------------------------------------------------------------
# Keyword regexes, so this UNDERCOUNTS: a review conveying noise as "I could hear every
# footstep upstairs" scores as a miss. Treat coverage as a lower bound, and read the
# structured-vs-unstructured gap rather than the absolute number.

ASPECT_PATTERNS = {
    "the location": r"\b(?:locat|neighborhood|nearby|walk(?:ing)?\s+distance|block[s]?\s+from|downtown|close to|around the corner|steps from)",
    "the price / value for money": r"\b(?:price[ds]?|pricing|cost|rate[s]?|value|expensive|cheap|afford|worth (?:it|the)|for what (?:we|i) paid|bargain|overpriced)",
    "room cleanliness": r"\b(?:clean|dirt(?:y|ier)|spotless|stain|dust|grime|hygien|immaculate|filth|housekeeping|tidy)",
    "how long the stay was": r"\b(?:\d+\s*(?:night|day|week)|one night|two nights|three nights|a week|weekend|stayed for|our stay|overnight)",
    "the staff": r"\b(?:staff|reception|front desk|concierge|manager|employee|housekeep|bellhop|porter|check[- ]?in)",
    "noise levels": r"\b(?:nois(?:e|y)|quiet|loud|sound(?:proof)?|hear(?:d|ing)?\s|thin walls|traffic outside|silent|peaceful)",
    "breakfast": r"\b(?:breakfast|buffet|continental|morning meal|coffee (?:bar|station)|omelet|pastri)",
}

PREAMBLE_LEAK = r"^\s*(?:sure|certainly|of course|here(?:'s| is)|review\s*:)"
AI_DISCLOSURE = r"\b(?:as an ai|language model|i cannot|i'm unable to|generated by)"


def opener_word(text: str) -> str:
    m = re.match(r"[^A-Za-z]*([A-Za-z']+)", str(text))
    return m.group(1).lower() if m else ""


def ngram_overlap(a: str, b: str, n: int = 6) -> int:
    """Longest run of n-grams from `b` that appears verbatim in `a`. Detects few-shot
    copying, which would make the few_shot cells parrots rather than a real condition."""
    aw, bw = str(a).lower().split(), str(b).lower().split()
    if len(bw) < n or len(aw) < n:
        return 0
    agrams = {" ".join(aw[i:i + n]) for i in range(len(aw) - n + 1)}
    return sum(1 for i in range(len(bw) - n + 1) if " ".join(bw[i:i + n]) in agrams)


# ---------------------------------------------------------------------------
# RNG replay
# ---------------------------------------------------------------------------

def reconstruct_instructions(gen: pd.DataFrame, examples_csv: Path, tolerance: float):
    """Recover the exact aspects / few-shot examples / opener each row was asked for.

    Replays the generator's per-cell RNG. Requires the run to have used a single seed and
    a contiguous rep_index range -- both true of any run the generator produced.
    """
    pool = ExamplePool(examples_csv)
    targets = {k: dict(v) for k, v in cfg.LENGTH_TARGETS.items()}
    combo_ordinal = {c: i for i, c in enumerate(ALL_CELLS)}

    # The replay reproduces the CURRENT prompt code. A CSV written before the opener draw
    # was added has an RNG stream offset by one call per review, so recovered aspects and
    # examples are wrong for every rep after the first. Stylometry does not depend on the
    # replay and stays valid either way.
    if "opener_move" not in gen.columns:
        print("\n  ! This CSV predates opener steering. The RNG stream has since changed,")
        print("    so sections 3 and 4 (structure, example_mode) are NOT valid for it.")
        print("    Sections 1, 6, 7, 8 are unaffected.")

    seeds = gen["gen_seed"].unique()
    if len(seeds) != 1:
        print(f"  ! multiple seeds {list(seeds)} in one file; replay skipped")
        return {}
    seed = int(seeds[0])
    n_per_cell = int(gen["rep_index"].max()) + 1

    recovered = {}
    for (length, sentiment, structure, example_mode) in ALL_CELLS:
        cell_id = f"{length}_{sentiment}_{structure}_{example_mode}"
        rng = random.Random(f"{seed}:{cell_id}")
        for rep in range(n_per_cell):
            ordinal = combo_ordinal[(length, sentiment, structure, example_mode)] \
                * n_per_cell + rep
            hotel = pool.hotels[ordinal % len(pool.hotels)]
            messages, opener_move = build_messages(
                length, sentiment, structure, example_mode, hotel, pool, targets, rng,
                tolerance,
            )
            sysmsg = messages[0]["content"]
            aspects = []
            m = re.search(r"\(no bullet points, no headings\): (.+?)\.\n", sysmsg)
            if m:
                aspects = [a.strip() for a in m.group(1).split(",")]
            recovered[(cell_id, rep)] = {
                "hotel": hotel,
                "aspects": aspects,
                "opener_move": opener_move,
                "user_msg": messages[1]["content"],
            }
    return recovered


# ---------------------------------------------------------------------------
# LLM sentiment judge
# ---------------------------------------------------------------------------

def judge_sentiment_llm(texts, url, model):
    """Ask the model to classify sentiment.

    Primary over a word-count lexicon on purpose: on the llama3.2 sample the lexicon
    scored negative reviews at 45.8% while the judge scored 100%, because mixed-tone
    reviews ("the bed was comfortable, but the AC rattled all night") tip positive on raw
    counts. The lexicon was the broken instrument, not the data.
    """
    out = []
    for t in texts:
        try:
            r = requests.post(
                url,
                json={
                    "model": model,
                    "messages": [
                        {"role": "system", "content":
                         "Classify the overall sentiment of the hotel review as exactly "
                         "one word: positive or negative. Output only that word."},
                        {"role": "user", "content": str(t)},
                    ],
                    "stream": False,
                    "options": {"temperature": 0},
                },
                timeout=cfg.REQUEST_TIMEOUT,
            )
            r.raise_for_status()
            v = r.json()["message"]["content"].strip().lower()
            out.append("positive" if "positive" in v else
                       "negative" if "negative" in v else "unknown")
        except Exception as e:
            out.append(f"error:{type(e).__name__}")
    return out



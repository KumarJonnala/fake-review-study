"""
Validate a generated review CSV on two fronts.

1. INSTRUCTION COMPLIANCE -- did each review obey the 16-cell factorial instruction it
   was actually given? The requested aspects and few-shot examples are not stored in the
   CSV, so they are recovered by replaying the generator's seeded RNG: the same
   `random.Random(f"{seed}:{cell_id}")` stream, the same hotel rotation, the same calls
   into `build_messages`. This imports the generator rather than reimplementing it, so
   the replay cannot drift from what actually ran.

2. STYLOMETRY vs the human corpus -- does the generated text carry giveaways that would
   let a classifier separate the LLM class for reasons unrelated to the study question?
   Every metric is reported LLM / real / human-fake side by side, because "66% start with
   I" only means something next to the 21% the real corpus does.

   The perfect-separator check is deliberately generic: it looks for ANY character
   appearing in the LLM output but effectively absent from both human classes, so the
   next artifact is caught without anyone knowing to look for it. That check exists
   because the en-dash slipped through once already, at 14.6% of LLM reviews against
   0.0% of 1592 human ones, caused by em-dashes in the prompt file itself.

Usage:
    python3 src/validate_generated.py                      # default output CSV
    python3 src/validate_generated.py --generated <csv>
    python3 src/validate_generated.py --no-judge           # skip the LLM sentiment judge
"""


def section(title):
    print(f"\n{'=' * 78}\n{title}\n{'=' * 78}")


def report_length(gen, tolerance):
    section("1. LENGTH")
    for name, g in gen.groupby("length"):
        lo, hi = length_band(cfg.LENGTH_TARGETS[name]["chars"], tolerance)
        print(f"  {name:6s} n={len(g):3d}  target={cfg.LENGTH_TARGETS[name]['chars']:4d} "
              f"band={lo}-{hi}  mean={g.n_chars.mean():7.1f}  "
              f"in-band={100 * g.in_length_band.mean():5.1f}%  "
              f"attempts={g.n_attempts.mean():.2f}")


def report_sentiment(gen, url, model, use_judge):
    section("2. SENTIMENT")
    if not use_judge:
        print("  (skipped: --no-judge)")
        return
    verdict = judge_sentiment_llm(gen.text.tolist(), url, model)
    gen = gen.assign(judged=verdict)
    for name, g in gen.groupby("sentiment"):
        ok = (g.judged == name).sum()
        print(f"  requested {name:8s} n={len(g):3d}  judge agrees {ok:3d} "
              f"({100 * ok / len(g):5.1f}%)")
    bad = gen[gen.judged.str.startswith("error")]
    if len(bad):
        print(f"  ! {len(bad)} judge calls errored")


def report_structure(gen, recovered):
    section("3. STRUCTURE (aspect coverage)")
    print("  Regex keyword matching, so these are LOWER BOUNDS. Read the structured-vs-")
    print("  unstructured gap, not the absolute rate.\n")

    rows = []
    for _, r in gen.iterrows():
        info = recovered.get((r.cell_id, r.rep_index))
        if not info or not info["aspects"]:
            continue
        hits = sum(
            1 for a in info["aspects"]
            if a in ASPECT_PATTERNS and re.search(ASPECT_PATTERNS[a], str(r.text), re.I)
        )
        rows.append({"length": r.length, "asked": len(info["aspects"]), "hit": hits})
    if not rows:
        print("  (no structured rows recovered)")
        return
    d = pd.DataFrame(rows)
    tot_a, tot_h = d.asked.sum(), d.hit.sum()
    print(f"  structured overall: {tot_h}/{tot_a} named aspects covered "
          f"({100 * tot_h / tot_a:.1f}%)")
    for L, g in d.groupby("length"):
        print(f"    {L:6s}: {g.hit.sum()}/{g.asked.sum()} "
              f"({100 * g.hit.sum() / g.asked.sum():5.1f}%)")
    print("\n  Short cells are expected to lag: ASPECTS_PER_REVIEW=%d will not fit in "
          "%d chars." % (cfg.ASPECTS_PER_REVIEW, cfg.LENGTH_TARGETS['short']['chars']))

    # Free-mention rate across ALL reviews, to show whether the manipulation bites at all.
    print("\n  Aspects mentioned per review (any aspect, structured vs not):")
    for S, g in gen.groupby("structure"):
        n = g.text.map(lambda t: sum(
            1 for p in ASPECT_PATTERNS.values() if re.search(p, str(t), re.I))).mean()
        print(f"    {S:12s}: {n:.2f} / {len(ASPECT_PATTERNS)}")


def report_example_mode(gen, recovered):
    section("4. EXAMPLE MODE (few-shot copying)")
    worst, n_any, n_fs = 0, 0, 0
    for _, r in gen.iterrows():
        if r.example_mode != "few_shot":
            continue
        info = recovered.get((r.cell_id, r.rep_index))
        if not info:
            continue
        n_fs += 1
        c = ngram_overlap(info["user_msg"], r.text, n=6)
        worst = max(worst, c)
        n_any += c > 0
    print(f"  few-shot rows reconstructed: {n_fs}")
    print(f"  reviews with any copied 6-gram: {n_any}   max copied 6-grams: {worst}")
    if worst > 5:
        print("  ! substantial copying: the few_shot cells may be parroting examples")


def report_opener(gen, recovered):
    section("5. OPENER COMPLIANCE")
    if "opener_move" not in gen.columns:
        print("  (no opener_move column: CSV predates opener steering)")
        return
    fw = gen.text.map(opener_word)
    first_person_sg = fw.isin(["i", "i'm", "i've", "id", "my"])
    first_person_pl = fw.isin(["we", "we've", "our", "us"])
    for mv, g in gen.groupby("opener_move"):
        sub_fw = g.text.map(opener_word)
        if mv.startswith("first person singular"):
            ok = sub_fw.isin(["i", "i'm", "i've", "my"]).mean()
        elif mv.startswith("first person plural"):
            ok = sub_fw.isin(["we", "we've", "our", "us"]).mean()
        else:
            # For the open-ended moves, the check is only that it did NOT fall back to
            # the default first-person opener.
            ok = 1 - sub_fw.isin(["i", "i'm", "i've", "we", "my", "our"]).mean()
        label = "opens as asked" if mv.startswith("first person") else "avoided I/We default"
        print(f"  {mv[:52]:54s} n={len(g):3d}  {label}: {100 * ok:5.1f}%")


def report_stylometry(gen, hum):
    section("6. STYLOMETRY vs HUMAN CORPUS")
    real = hum[hum.Binary_label == cfg.REAL_LABEL].text.astype(str)
    fake = hum[hum.Binary_label == cfg.FAKE_LABEL].text.astype(str)
    llm = gen.text.astype(str)
    sets = [("LLM", llm), ("real", real), ("human-fake", fake)]

    print(f"  {'metric':32s} {'LLM':>10s} {'real':>10s} {'human-fake':>12s}")
    print("  " + "-" * 68)

    def row(name, fn):
        vals = [fn(s) for _, s in sets]
        print(f"  {name:32s} {vals[0]:9.1f}% {vals[1]:9.1f}% {vals[2]:11.1f}%")

    row("starts with 'I'", lambda s: 100 * s.map(opener_word).eq("i").mean())
    row("starts with I/We/My/Our",
        lambda s: 100 * s.map(opener_word).isin(["i", "we", "my", "our"]).mean())
    row("contains em-dash —", lambda s: 100 * s.str.contains("—").mean())
    row("contains en-dash –", lambda s: 100 * s.str.contains("–").mean())
    row("contains spaced hyphen ' - '", lambda s: 100 * s.str.contains(" - ").mean())
    row("contains any hyphen", lambda s: 100 * s.str.contains("-").mean())
    row("contains semicolon", lambda s: 100 * s.str.contains(";").mean())

    # Opener diversity, bootstrapped to the LLM sample size so the numbers are comparable.
    n = len(llm)
    boots = [real.sample(n, random_state=i).map(opener_word).nunique() for i in range(200)]
    lo, hi = pd.Series(boots).quantile([0.025, 0.975])
    got = llm.map(opener_word).nunique()
    flag = "OK" if lo <= got <= hi else "OUTSIDE real-corpus range"
    print(f"\n  distinct openers in {n} reviews: LLM={got}  "
          f"real 95% range={lo:.0f}-{hi:.0f}   -> {flag}")
    print("  LLM top openers:", Counter(llm.map(opener_word)).most_common(6))


def report_perfect_separators(gen, hum):
    section("7. PERFECT SEPARATORS (generic artifact scan)")
    print("  Any character common in LLM output but effectively absent from BOTH human")
    print("  classes is a free label for a classifier. This scan is deliberately generic:")
    print("  the en-dash slipped through once already because nobody was looking for it.\n")

    llm = gen.text.astype(str)
    real = hum[hum.Binary_label == cfg.REAL_LABEL].text.astype(str)
    fake = hum[hum.Binary_label == cfg.FAKE_LABEL].text.astype(str)

    chars = {c for t in llm for c in t if not c.isalnum() and not c.isspace()}
    flagged = []
    for c in sorted(chars):
        lr = llm.str.contains(re.escape(c)).mean()
        rr = real.str.contains(re.escape(c)).mean()
        fr = fake.str.contains(re.escape(c)).mean()
        if lr > 0.01 and rr < 0.001 and fr < 0.001:
            flagged.append((c, lr, rr, fr))

    if not flagged:
        print("  PASS: no character separates the LLM class outright.")
    else:
        print("  FAIL: these characters are near-perfect giveaways --")
        for c, lr, rr, fr in flagged:
            print(f"    {c!r} (U+{ord(c):04X})  LLM {100 * lr:5.1f}%   "
                  f"real {100 * rr:.2f}%   human-fake {100 * fr:.2f}%")
    return flagged


def report_hygiene(gen):
    section("8. HYGIENE")
    t = gen.text.astype(str)
    print(f"  preamble leaks:      {t.str.contains(PREAMBLE_LEAK, case=False, regex=True).sum()}")
    print(f"  AI self-disclosure:  {t.str.contains(AI_DISCLOSURE, case=False, regex=True).sum()}")
    print(f"  exact duplicates:    {len(t) - t.nunique()}")
    print(f"  hotels used:         {gen.Category.nunique()} / {len(ExamplePool(cfg.DEFAULT_EXAMPLES_CSV).hotels)}")
    counts = gen.Category.value_counts()
    if len(counts) > 1:
        print(f"  per-hotel spread:    min={counts.min()} max={counts.max()}")


